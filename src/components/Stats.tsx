import { useState } from "react";
import { useApp } from "../App";
import type { Mode } from "../lib/types";
import { confidenceLabel, describeTheta } from "../lib/cefr";
import { SKILL_LABEL, accuracyBySkill, costThisMonth, recentWords, streakDays, totalMinutes } from "../lib/stats";
import { LevelChart } from "./LevelChart";
import { LevelLine } from "./Home";

export function Stats() {
  const { sessions, progress, settings } = useApp();
  const [modeFilter, setModeFilter] = useState<Mode | "all">("all");

  const overall = describeTheta((progress.reading.theta + progress.listening.theta) / 2);
  const acc = accuracyBySkill(sessions, modeFilter === "all" ? undefined : modeFilter);
  const recent = sessions.slice(-15).reverse();
  const words = recentWords(sessions);

  return (
    <>
      <header className="topbar">
        <h1 style={{ margin: 0 }}>Progress</h1>
      </header>

      <div className="tiles">
        <div className="tile">
          <div className="v">{overall.level}</div>
          <div className="l">Estimated level (both skills)</div>
        </div>
        <div className="tile">
          <div className="v">{sessions.length}</div>
          <div className="l">Sessions</div>
        </div>
        <div className="tile">
          <div className="v">{totalMinutes(sessions)}</div>
          <div className="l">Minutes practised</div>
        </div>
        <div className="tile">
          <div className="v">{streakDays(sessions)}</div>
          <div className="l">Day streak</div>
        </div>
      </div>

      <section className="card">
        <h2>Estimated CEFR level</h2>
        <LevelLine label="Reading" theta={progress.reading.theta} n={progress.reading.n} />
        <LevelLine label="Listening" theta={progress.listening.theta} n={progress.listening.n} />
        {sessions.length > 0 ? (
          <>
            <LevelChart sessions={sessions} start={{ reading: settings.startLevel, listening: settings.startLevel }} />
            <details>
              <summary className="small">Show as table</summary>
              <table className="data">
                <thead>
                  <tr>
                    <th>Date</th>
                    <th>Skill</th>
                    <th>Text</th>
                    <th>Score</th>
                    <th>Estimate after</th>
                  </tr>
                </thead>
                <tbody>
                  {sessions
                    .slice()
                    .reverse()
                    .map((s) => {
                      const d = describeTheta(s.thetaAfter);
                      return (
                        <tr key={s.id}>
                          <td>{new Date(s.date).toLocaleDateString()}</td>
                          <td>{s.mode}</td>
                          <td>{s.level}</td>
                          <td>{Math.round(s.score * 100)}%</td>
                          <td>
                            {d.level} {Math.round(d.progress * 100)}%
                          </td>
                        </tr>
                      );
                    })}
                </tbody>
              </table>
            </details>
          </>
        ) : (
          <p className="small muted">Your chart appears after the first session.</p>
        )}
        <details className="small" style={{ marginTop: 8 }}>
          <summary>How is this estimated?</summary>
          <p className="muted" style={{ marginTop: 6 }}>
            Every text is written for a CEFR level (A2, B1, B2 …). After each session your score is compared with what
            someone exactly at your current estimate would be expected to score on a text of that level. Scoring above
            that moves the estimate up, below it moves it down. Steps get smaller as more sessions accumulate. Texts are
            pitched slightly above your estimate.
          </p>
          <p className="muted">
            Limits: this is not an official test. The texts and questions are generated by AI, so their difficulty
            varies, and the estimate covers only reading and listening (not speaking or writing). Confidence: reading{" "}
            {confidenceLabel(progress.reading.n)}, listening {confidenceLabel(progress.listening.n)}.
          </p>
        </details>
      </section>

      <section className="card">
        <div className="row spread" style={{ marginBottom: 8 }}>
          <h2 style={{ margin: 0 }}>Accuracy by task type</h2>
        </div>
        <div className="seg" role="group" aria-label="Filter by skill" style={{ marginBottom: 12 }}>
          {(["all", "reading", "listening"] as const).map((m) => (
            <button key={m} aria-pressed={modeFilter === m} onClick={() => setModeFilter(m)}>
              {m === "all" ? "Both" : m === "reading" ? "Reading" : "Listening"}
            </button>
          ))}
        </div>
        {acc.map((a) => (
          <div className="hbar" key={a.skill} title={`${SKILL_LABEL[a.skill]}: ${a.n ? Math.round(a.pct * 100) + "% over " + a.n + " tasks" : "no tasks yet"}`}>
            <span>{SKILL_LABEL[a.skill]}</span>
            <span className="track">
              <span className="fill" style={{ display: "block", width: `${a.n ? Math.max(2, a.pct * 100) : 0}%` }} />
            </span>
            <span className="val">{a.n ? `${Math.round(a.pct * 100)}%` : "–"}</span>
          </div>
        ))}
      </section>

      <section className="card">
        <h2>Recent sessions</h2>
        {recent.length === 0 ? (
          <p className="small muted">None yet.</p>
        ) : (
          <ul className="list">
            {recent.map((s) => (
              <li key={s.id}>
                <div className="row spread">
                  <span lang="el" style={{ fontWeight: 600 }}>
                    {s.title}
                  </span>
                  <span className="small">{Math.round(s.score * 100)}%</span>
                </div>
                <div className="tiny">
                  {new Date(s.date).toLocaleDateString()} · {s.mode} · {s.level} · {s.source.kind === "ai" ? "everyday" : s.source.kind} ·{" "}
                  {Math.round((s.exposureSec + s.tasksSec) / 60)} min
                  {s.source.url && (
                    <>
                      {" · "}
                      <a href={s.source.url} target="_blank" rel="noopener noreferrer">
                        original
                      </a>
                    </>
                  )}
                </div>
              </li>
            ))}
          </ul>
        )}
      </section>

      {words.length > 0 && (
        <details className="card">
          <summary>Words from your texts ({words.length})</summary>
          <dl className="gloss" style={{ marginTop: 8 }}>
            {words.map((g, i) => (
              <div key={i} style={{ display: "contents" }}>
                <dt lang="el">{g.greek}</dt>
                <dd>{g.english}</dd>
              </div>
            ))}
          </dl>
        </details>
      )}

      <section className="card soft small">
        Estimated API cost this month: <strong>${costThisMonth(sessions).toFixed(2)}</strong> (from token counts × list
        prices; your Anthropic Console shows the actual bill).
      </section>
    </>
  );
}
