import { useState } from "react";
import { useApp } from "../App";
import type { Mode } from "../lib/types";
import { confidenceLabel, describeTheta, overallTheta } from "../lib/cefr";
import { SKILL_LABEL, accuracyBySkill, costThisMonth, recentWords, streakDays, totalMinutes } from "../lib/stats";
import { LevelChart } from "./LevelChart";
import { allMonths, getMonth, isComplete, monthLabel } from "../lib/placement";
import { placementMonth } from "./PlacementView";
import { loadLookups } from "../lib/glosses";
import { LevelLine, WritingLine } from "./Home";

export function Stats() {
  const { sessions, progress, settings } = useApp();
  const [modeFilter, setModeFilter] = useState<Mode | "all">("all");

  const overall = describeTheta(overallTheta(progress));
  const acc = accuracyBySkill(sessions, modeFilter === "all" ? undefined : modeFilter);
  const recent = sessions.slice(-15).reverse();
  const words = recentWords(sessions);
  const looked = loadLookups().slice().reverse();

  return (
    <>
      <header className="topbar">
        <h1 style={{ margin: 0 }}>Progress</h1>
      </header>

      <div className="tiles">
        <div className="tile">
          <div className="v">{overall.level}</div>
          <div className="l">Estimated level (overall)</div>
        </div>
        <div className="tile">
          <div className="v">{sessions.length}</div>
          <div className="l">Sessions</div>
        </div>
        <div className="tile">
          <div className="v">{totalMinutes(sessions)}</div>
          <div className="l">Minutes practised</div>
        </div>
        <div className="tile">
          <div className="v">{streakDays(sessions)}</div>
          <div className="l">Day streak</div>
        </div>
      </div>

      <section className="card">
        <h2>Estimated CEFR level</h2>
        <LevelLine label="Reading" theta={progress.reading.theta} n={progress.reading.n} />
        <LevelLine label="Listening" theta={progress.listening.theta} n={progress.listening.n} />
        <WritingLine />
        {sessions.length > 0 ? (
          <>
            <LevelChart
              sessions={sessions}
              start={{ reading: settings.startLevel, listening: settings.startLevel }}
              current={{
                reading: progress.reading.theta,
                listening: progress.listening.theta,
                writing: progress.writing?.n ? progress.writing.theta : undefined,
              }}
            />
            <p className="tiny" style={{ marginTop: 4 }}>
              Dots are sessions; a dashed line leads to your current estimate (e.g. after the last session of that skill,
              or after setting your level by hand).
            </p>
            <details>
              <summary className="small">Show as table</summary>
              <table className="data">
                <thead>
                  <tr>
                    <th>Date</th>
                    <th>Skill</th>
                    <th>Text</th>
                    <th>Score</th>
                    <th>Estimate after</th>
                    <th>Writing</th>
                  </tr>
                </thead>
                <tbody>
                  {sessions
                    .slice()
                    .reverse()
                    .map((s) => {
                      const d = describeTheta(s.thetaAfter);
                      return (
                        <tr key={s.id}>
                          <td>{new Date(s.date).toLocaleDateString()}</td>
                          <td>{s.mode}</td>
                          <td>{s.level}</td>
                          <td>{Math.round(s.score * 100)}%</td>
                          <td>
                            {d.level} {Math.round(d.progress * 100)}%
                          </td>
                          <td>{s.writingLevel ?? "–"}</td>
                        </tr>
                      );
                    })}
                </tbody>
              </table>
            </details>
          </>
        ) : (
          <p className="small muted">Your chart appears after the first session.</p>
        )}
        <details className="small" style={{ marginTop: 8 }}>
          <summary>How is this estimated?</summary>
          <p className="muted" style={{ marginTop: 6 }}>
            Every text is written for a CEFR level (A2, B1, B2 …). After each session your score is compared with what
            someone exactly at your current estimate would be expected to score on a text of that level. Scoring above
            that moves the estimate up, below it moves it down. Steps get smaller as more sessions accumulate. Texts are
            pitched slightly above your estimate.
          </p>
          <p className="muted">
            Limits: this is not an official test. The texts and questions are generated by AI, so their difficulty
            varies. Writing is estimated differently: the grader judges which CEFR level each written answer shows
            (from range, accuracy and coherence), and these judgements are averaged, with more weight on recent ones.
            With answers of 2–3 sentences this is rough and can understate higher levels. Speaking is not covered.
            Confidence: reading {confidenceLabel(progress.reading.n)}, listening {confidenceLabel(progress.listening.n)}
            {progress.writing?.n ? `, writing ${confidenceLabel(progress.writing.n)}` : ""}.
          </p>
        </details>
      </section>

      <PlacementHistory />

      <section className="card">
        <div className="row spread" style={{ marginBottom: 8 }}>
          <h2 style={{ margin: 0 }}>Accuracy by task type</h2>
        </div>
        <div className="seg" role="group" aria-label="Filter by skill" style={{ marginBottom: 12 }}>
          {(["all", "reading", "listening"] as const).map((m) => (
            <button key={m} aria-pressed={modeFilter === m} onClick={() => setModeFilter(m)}>
              {m === "all" ? "Both" : m === "reading" ? "Reading" : "Listening"}
            </button>
          ))}
        </div>
        {acc.map((a) => (
          <div className="hbar" key={a.skill} title={`${SKILL_LABEL[a.skill]}: ${a.n ? Math.round(a.pct * 100) + "% over " + a.n + " tasks" : "no tasks yet"}`}>
            <span>{SKILL_LABEL[a.skill]}</span>
            <span className="track">
              <span className="fill" style={{ display: "block", width: `${a.n ? Math.max(2, a.pct * 100) : 0}%` }} />
            </span>
            <span className="val">{a.n ? `${Math.round(a.pct * 100)}%` : "–"}</span>
          </div>
        ))}
      </section>

      <section className="card">
        <h2>Recent sessions</h2>
        {recent.length === 0 ? (
          <p className="small muted">None yet.</p>
        ) : (
          <ul className="list">
            {recent.map((s) => (
              <li key={s.id}>
                <div className="row spread">
                  <span lang="el" style={{ fontWeight: 600 }}>
                    {s.title}
                  </span>
                  <span className="small">{Math.round(s.score * 100)}%</span>
                </div>
                <div className="tiny">
                  {new Date(s.date).toLocaleDateString()} · {s.mode} · {s.level} · {s.source.kind === "ai" ? "everyday" : s.source.kind} ·{" "}
                  {Math.round((s.exposureSec + s.tasksSec) / 60)} min
                  {s.source.url && (
                    <>
                      {" · "}
                      <a href={s.source.url} target="_blank" rel="noopener noreferrer">
                        original
                      </a>
                    </>
                  )}
                </div>
              </li>
            ))}
          </ul>
        )}
      </section>

      {looked.length > 0 && (
        <details className="card" open>
          <summary>Words you looked up ({looked.length})</summary>
          <dl className="gloss" style={{ marginTop: 8 }}>
            {looked.slice(0, 200).map((g, i) => (
              <div key={i} style={{ display: "contents" }}>
                <dt lang="el">{g.lemma || g.form}</dt>
                <dd>
                  {g.en}
                  {g.lemma && g.lemma !== g.form && (
                    <span className="tiny" lang="el">
                      {" "}
                      · {g.form}
                    </span>
                  )}
                </dd>
              </div>
            ))}
          </dl>
        </details>
      )}

      {words.length > 0 && (
        <details className="card">
          <summary>Words from your texts ({words.length})</summary>
          <dl className="gloss" style={{ marginTop: 8 }}>
            {words.map((g, i) => (
              <div key={i} style={{ display: "contents" }}>
                <dt lang="el">{g.greek}</dt>
                <dd>{g.english}</dd>
              </div>
            ))}
          </dl>
        </details>
      )}

      <section className="card soft small">
        Estimated API cost this month: <strong>${costThisMonth(sessions).toFixed(2)}</strong> (from token counts × list
        prices; your Anthropic Console shows the actual bill).
      </section>
    </>
  );
}

/** Past placement tests, and a way to take this month's test early. */
function PlacementHistory() {
  const { navigate, keyState } = useApp();
  const done = allMonths().filter((m) => m.results.reading || m.results.listening);
  const current = getMonth(placementMonth());
  const fmt = (t: number) => {
    const d = describeTheta(t);
    return `${d.level} ${Math.round(d.progress * 100)}%`;
  };
  return (
    <section className="card">
      <h2>Placement tests</h2>
      {done.length === 0 ? (
        <p className="small muted">
          A longer test at the end of each month (it appears on the home screen in the last week) to recalibrate your
          level.
        </p>
      ) : (
        <ul className="list small">
          {done
            .slice()
            .reverse()
            .map((m) => (
              <li key={m.month}>
                <strong>{monthLabel(m.month)}</strong>
                {m.results.reading && <> · reading {fmt(m.results.reading.theta)}</>}
                {m.results.listening && <> · listening {fmt(m.results.listening.theta)}</>}
                {m.results.reading?.writing && <> · writing {m.results.reading.writing.level}</>}
                {m.applied === true ? " · applied" : m.applied === false ? " · kept current levels" : ""}
              </li>
            ))}
        </ul>
      )}
      {!isComplete(current) && (
        <button className="btn" disabled={keyState !== "ready"} onClick={() => navigate("placement")}>
          {current.results.reading || current.results.listening ? "Continue" : "Take"} this month's placement test
        </button>
      )}
    </section>
  );
}

